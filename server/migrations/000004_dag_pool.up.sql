-- Пул дага: пул слотов по умолчанию для всех его тасков. Задаётся из
-- админки (при регистрации или позже), пусто — пул берётся из кода таска,
-- а если и там пусто — 'default'. Резолв при триггере рана
-- (task_instance.pool денормализован для claim-запроса очереди), поэтому
-- смена пула действует со следующего рана.
alter table dag add column pool text not null default '';

-- Желаемый пул нового дага, как и остальные настройки регистрации:
-- применяется только если даг создаётся впервые.
alter table dag_registration add column pool text;
